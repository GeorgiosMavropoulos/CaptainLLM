"""This file contains the script to feed GPT2's answers to an external model to use it as a judge"""
from fastapi import FastAPI,HTTPException, status
from dotenv import load_dotenv
import os
import json

import ollama
import urllib.request
#Create the application instance
app = FastAPI()
load_dotenv()

class QueryModel:
   def __init__(self):
      
    
    self.ollama_model = os.getenv('ollama_model')
    self.url = os.getenv('ollama_url')
    self.client =  ollama.Client(host=self.url)
    self.prompt = """Below, you will receive an instruction, an optional input, an expected output, and the response generated by my fine-tuned model.

    Evaluate the model's response by comparing it with the expected output and considering how accurately, completely, and relevantly it answers the instruction.
    Take into account that this model wasn't trained to the given test questions
    Assign a score from 0 to 100, where:
    - 0 means the response is completely incorrect, irrelevant, or fails to answer the instruction.
    - 50 means the response is partially correct but contains significant errors or omissions.
    - 100 means the response is fully correct, relevant, and sufficiently complete.

    Do not require the model's response to use the exact wording of the expected output. Accept alternative answers that convey the same meaning.

    Return a brief explanation of your evaluation and the final score.

    Return your evaluation in this JSON format:
    {
    "question": "What are the three primary colors?",
    "expected_output": "Red, yellow, and blue.",
    "model_response": "Red, green, and blue.",
    "score": 50,
    "reason": "The response identifies red and blue correctly but gives green instead of yellow."
    }

    **Evaluation guidelines:**

- The model response is generated by a model being evaluated on a test dataset that it may not have encountered during training.
- Evaluate the response based on its factual correctness, semantic meaning, completeness, and relevance to the instruction.
- Do not require the model response to match the expected output word-for-word.
- Accept semantically equivalent answers, even when they use different wording or sentence structures.
- Do not penalize a response merely because it is phrased differently from the expected output.
- Award partial credit when the response is partially correct, and deduct points for factual errors, missing important information, or irrelevant content.
- The fact that a question may be unseen during training must not increase the score by itself. Score the quality of the response, not the difficulty of the task.


    """


    #method to send queries to the model
   def send_query(self, prompt, model):
        """This functions extract the json data from the file and send them one-by-one to the extran LLM"""
        questions  =[]
        scores = [] #create a list to keep all the scores
        average_score = 0
        #read data from json file
        with open("C:/Users/Overkill/Desktop/train-llm/BaseLLM/InstructionLLM/instruction-data-with-response.json","r",encoding='utf-8') as file:
            data = json.load(file)

        #loop through data to extract the json one by one
        for i in data[:56]:
         question_response_set = [
            f"Instruction:{i["instruction"]}",
            f"Input:{i["input"]}",
            f"Expected response:{i['expected_output']}",
            f"Model's resposne:{i['model_response']}"

        ]  

         #append question-response-set to the questions list
         questions.append(question_response_set)

        #set up the final query to send to the llm
         final_query = (
            f"{prompt}\n\n"
            f"Evaluate this example:\n{question_response_set}"
        )

         #send the query and receive model's response
         response =  self.client.chat(
            model=model,
            messages=[
                {
                    "role": "user",
                    "content": final_query
                }
            ],
            format="json"
        )

         #get back the response
         result = json.loads(response.message.content)
         questions.append(result) #append the result into questions list
         #get score
         
         score = result['score']
         scores.append(score)
         #get score's sum
         scores_total = sum(scores)
         #find the average of scores
         average = f'Average score:{scores_total / len(scores)}'
        

        return questions,average


#create a class instance
query_evaluation_model = QueryModel()
#create the endpoint to interact with hermes
@app.post('/query',status_code=status.HTTP_201_CREATED)
def chat_with_model():
        try:
            #call the send query method to send the query to the model
            questions, average = query_evaluation_model.send_query(query_evaluation_model.prompt,
            query_evaluation_model.ollama_model)
            return {"results": [questions, average]}
        except Exception as e:
            raise HTTPException(status_code=500, detail=str(e))




 